from pathlib import Path

import numpy as np
import matplotlib.pyplot as plt
from matplotlib.ticker import AutoMinorLocator


labels = ["RANS-GNN", "VortexAD", "OpenFOAM"]

datasets = [
    (alpha_1, lift_1, drag_1, moment_1),
    (alpha_2, lift_2, drag_2, moment_2),
    (alpha_3, lift_3, drag_3, moment_3),
]

plots = [
    ("Lift Curve", "Lift (kN)", "plots/lift_curve.png", 0),
    ("Drag Curve", "Drag (kN)", "plots/drag_curve.png", 1),
    ("Lift-to-Drag Ratio", "L/D", "plots/lift_to_drag_curve.png", 2),
    ("Pitching Moment Curve", "Moment (kN·m)", "plots/moment_curve.png", 3),
]


# ---------------------------------------------------------------------
# Minor styling improvements
# ---------------------------------------------------------------------
# Minor styling improvements
plt.rcParams.update({
    "font.size": 10,
    "axes.titlesize": 12,
    "axes.labelsize": 11,
    "axes.titleweight": "semibold",
    "legend.fontsize": 9,
    "xtick.labelsize": 9,
    "ytick.labelsize": 9,
    "lines.linewidth": 1.2,
    "savefig.dpi": 300,
})

colors = ["#0072B2", "#D55E00", "#009E73"]
markers = ["o", "s", "^"]

Path("plots").mkdir(parents=True, exist_ok=True)

for title, ylabel, filename, plot_type in plots:
    fig, ax = plt.subplots(figsize=(7, 5))

    for (
        (alpha, lift, drag, moment),
        label,
        color,
        marker,
    ) in zip(datasets, labels, colors, markers):

        if "Custom" in label:
            continue

        if plot_type == 0:
            values = lift / 1e3
        elif plot_type == 1:
            values = drag / 1e3
        elif plot_type == 2:
            values = lift / drag
        else:
            values = moment / 1e3

        ax.plot(
            alpha,
            values,
            label=label,
            color=color,
            marker=marker,
            linestyle="-",
            linewidth=1.2,
            markersize=4.0,
            markerfacecolor=color,
            markeredgecolor=color,
            markeredgewidth=0.8,
        )

    ax.set_xlabel("Angle of Attack (deg)")
    ax.set_ylabel(ylabel)
    ax.set_title(title, pad=10)

    ax.set_xticks(alpha_1)
    ax.xaxis.set_minor_locator(AutoMinorLocator(2))
    ax.yaxis.set_minor_locator(AutoMinorLocator(2))

    ax.grid(
        True,
        which="major",
        linewidth=0.6,
        alpha=0.30,
    )
    ax.grid(
        True,
        which="minor",
        linewidth=0.35,
        alpha=0.15,
    )

    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)

    ax.tick_params(
        axis="both",
        which="major",
        direction="out",
        length=4,
    )
    ax.tick_params(
        axis="both",
        which="minor",
        direction="out",
        length=2,
    )

    ax.legend(
        frameon=False,
        loc="best",
        handlelength=2.2,
    )

    fig.tight_layout()
    fig.savefig(
        filename,
        dpi=300,
        bbox_inches="tight",
        facecolor="white",
    )
    plt.show()
    plt.close(fig)